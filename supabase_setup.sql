create table if not exists public.factory_catalogo_produtos (
  id text primary key, nome text not null, valor text not null default '', preco numeric(10,2) not null check (preco >= 0),
  descricao text not null default '', categoria text not null default 'Açaí', ativo boolean not null default true,
  ordem integer not null default 0, atualizado_em timestamptz not null default now()
);
create table if not exists public.factory_catalogo_adicionais (
  id text primary key, nome text not null, preco numeric(10,2) not null check (preco >= 0),
  categoria text not null, emoji text not null default '➕', ativo boolean not null default true,
  ordem integer not null default 0, atualizado_em timestamptz not null default now()
);
create table if not exists public.pedidos (
  id bigint generated by default as identity primary key, nome text not null, endereco text not null, telefone text not null,
  pagamento text not null check (pagamento in ('dinheiro','pix','cartao','credito','debito','cartão de crédito/débito')),
  total numeric(10,2) not null default 0 check (total >= 0),
  status text not null default 'Pendente' check (status in ('Pendente','Em preparo','Saiu para entrega','Entregue','Cancelado')),
  criado_em timestamptz not null default now()
);
create table if not exists public.itens_pedido (
  id bigint generated by default as identity primary key, pedido_id bigint not null references public.pedidos(id) on delete cascade,
  nome text not null, tamanho text, qtd integer not null default 1 check (qtd between 1 and 30),
  preco numeric(10,2) not null check (preco >= 0), complementos text[] not null default '{}', observacao text
);
create table if not exists public.factory_admins (
  user_id uuid primary key references auth.users(id) on delete cascade, criado_em timestamptz not null default now()
);

